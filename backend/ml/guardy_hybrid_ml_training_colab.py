def normalize_external_dataset(raw_df, source_name):
    column_map = {str(c).lower().strip(): c for c in raw_df.columns}

    url_col = None
    for candidate in ["url", "urls", "website", "link"]:
        if candidate in column_map:
            url_col = column_map[candidate]
            break

    label_col = None
    for candidate in ["label", "classlabel", "class", "type", "status", "target"]:
        if candidate in column_map:
            label_col = column_map[candidate]
            break

    if url_col is None or label_col is None:
        print("Skipping", source_name, "- could not find URL/label columns")
        print("Columns:", list(raw_df.columns))
        return pd.DataFrame(columns=["url", "label", "source"])

    out = raw_df[[url_col, label_col]].rename(columns={url_col: "url", label_col: "raw_label"})
    out["url"] = out["url"].astype(str).str.strip()
    out = out.dropna(subset=["url", "raw_label"])

    raw_label = out["raw_label"]
    source_lower = source_name.lower()

    if pd.api.types.is_numeric_dtype(raw_label):
        labels = raw_label.astype(int)
        unique_values = set(labels.dropna().unique().tolist())
        if unique_values.issubset({0, 1}):
            # PhiUSIIL and LegitPhish use 1 = legitimate, 0 = phishing.
            if "phiusiil" in source_lower or "legitphish" in source_lower:
                out["label"] = labels.map({1: 0, 0: 1})
            else:
                out["label"] = labels
        else:
            print("Skipping", source_name, "- unsupported labels:", sorted(unique_values))
            return pd.DataFrame(columns=["url", "label", "source"])
    else:
        text = raw_label.astype(str).str.lower().str.strip()
        unique_text = set(text.dropna().unique().tolist())
        if unique_text.issubset({"0", "1"}):
            if "phiusiil" in source_lower or "legitphish" in source_lower:
                out["label"] = text.map({"1": 0, "0": 1})
            else:
                out["label"] = text.astype(int)
        else:
            mapping = {
                "legitimate": 0, "legit": 0, "benign": 0, "safe": 0, "good": 0,
                "phishing": 1, "phish": 1, "malicious": 1, "bad": 1,
            }
            out["label"] = text.map(mapping)

    out = out[["url", "label"]].dropna()
    out["label"] = out["label"].astype(int)
    out["url"] = out["url"].map(normalize_url)
    out = out.dropna(subset=["url"]).drop_duplicates(subset=["url"])
    out["source"] = source_name

    if len(out) > MAX_OPTIONAL_DATASET_ROWS:
        out = (
            out.groupby("label", group_keys=False)
            .apply(lambda x: x.sample(min(len(x), MAX_OPTIONAL_DATASET_ROWS // 2), random_state=RANDOM_SEED))
            .sample(frac=1.0, random_state=RANDOM_SEED)
            .reset_index(drop=True)
        )
    return out



def normalize_url(value):
    value = str(value or "").strip()
    if not value or value.lower() == "nan":
        return None
    if "://" not in value:
        value = "https://" + value
    return value


def make_df(urls, label, source):
    cleaned = []
    for url in urls:
        norm = normalize_url(url)
        if norm:
            cleaned.append(norm)
    return pd.DataFrame({"url": cleaned, "label": int(label), "source": source})



def proba_phishing(model, X_values):
    proba = model.predict_proba(X_values)
    return proba[:, 1] if getattr(proba, "ndim", 1) == 2 else np.asarray(proba).ravel()


def false_positive_rate(y_true, y_pred):
    tn, fp, fn, tp = confusion_matrix(y_true, y_pred, labels=[0, 1]).ravel()
    return fp / max(fp + tn, 1)


def manual_cross_validate(estimator, X_values, y_values, cv):
    """Manual CV avoids sklearn cross_validate calling broken XGBoost sklearn tags."""
    fold_rows = []
    for fold, (train_idx, valid_idx) in enumerate(cv.split(X_values, y_values), start=1):
        model = copy.deepcopy(estimator)
        X_fold_train = X_values.iloc[train_idx] if hasattr(X_values, "iloc") else X_values[train_idx]
        X_fold_valid = X_values.iloc[valid_idx] if hasattr(X_values, "iloc") else X_values[valid_idx]
        y_fold_train = y_values[train_idx]
        y_fold_valid = y_values[valid_idx]

        model.fit(X_fold_train, y_fold_train)
        prob = proba_phishing(model, X_fold_valid)
        pred = (prob >= 0.5).astype(int)
        fold_rows.append({
            "fold": fold,
            "f1": f1_score(y_fold_valid, pred, zero_division=0),
            "precision": precision_score(y_fold_valid, pred, zero_division=0),
            "recall": recall_score(y_fold_valid, pred, zero_division=0),
            "roc_auc": roc_auc_score(y_fold_valid, prob),
        })
    return pd.DataFrame(fold_rows)



def read_urlhaus_csv(path):
    path = Path(path)
    read_kwargs = dict(comment="#", header=None, low_memory=False, on_bad_lines="skip")

    # URLhaus may be served as ZIP/gzip bytes depending on endpoint/proxy behavior.
    if zipfile.is_zipfile(path):
        with zipfile.ZipFile(path, "r") as zf:
            csv_names = [name for name in zf.namelist() if name.lower().endswith((".csv", ".txt"))]
            if not csv_names:
                raise ValueError("URLhaus archive did not contain CSV/TXT")
            with zf.open(csv_names[0]) as f:
                return pd.read_csv(f, encoding="latin-1", **read_kwargs)

    for encoding in ["utf-8", "latin-1", "cp1252"]:
        try:
            return pd.read_csv(path, encoding=encoding, **read_kwargs)
        except UnicodeDecodeError:
            continue
    return pd.read_csv(path, encoding="latin-1", **read_kwargs)


